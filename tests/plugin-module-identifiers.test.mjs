import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import test from 'node:test'

// A plugin module that uses a name it never imported still parses and still loads: the
// ReferenceError only fires on the code path that touches it, so a missing import can ship
// and only surface as "X is not defined" in the middle of a turn. This audit walks the
// real host-side modules and fails on any identifier that is neither declared nor imported.

const require = createRequire(import.meta.url)
const acorn = require('acorn')

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const LIB = path.join(ROOT, 'tavern-plugin/lib')

// Runtime provided by Node, the host or the platform; the audit only looks for module-scope mistakes.
const GLOBALS = new Set(Object.getOwnPropertyNames(globalThis).concat([
  'undefined', 'NaN', 'Infinity', 'arguments', 'require', 'module', 'exports', '__dirname', '__filename', 'global'
]))

// vendor/ holds upstream bundles, client.js is the browser bundle (its own global surface), and
// host/mod-*.mjs are generated by bin/build-tavern-mods.mjs.
function audited(file) {
  const rel = path.relative(LIB, file)
  if (rel.startsWith('vendor' + path.sep)) return false
  if (rel === 'client.js') return false
  if (/^host[\\/]mod-[^\\/]+\.mjs$/.test(rel)) return false
  return true
}

function listModules(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) listModules(full, out)
    else if (/\.m?js$/.test(entry.name) && audited(full)) out.push(full)
  }
  return out
}

function walk(node, visit, parent = null, key = null) {
  if (!node || typeof node.type !== 'string') return
  visit(node, parent, key)
  for (const name of Object.keys(node)) {
    if (name === 'loc' || name === 'range' || name === 'start' || name === 'end') continue
    const value = node[name]
    if (Array.isArray(value)) {
      for (const child of value) walk(child, visit, node, name)
    } else if (value && typeof value.type === 'string') {
      walk(value, visit, node, name)
    }
  }
}

function patternNames(pattern, out) {
  if (!pattern) return
  switch (pattern.type) {
    case 'Identifier': out.add(pattern.name); break
    case 'ObjectPattern':
      for (const property of pattern.properties) {
        if (property.type === 'RestElement') patternNames(property.argument, out)
        else patternNames(property.value, out)
      }
      break
    case 'ArrayPattern': for (const element of pattern.elements) patternNames(element, out); break
    case 'RestElement': patternNames(pattern.argument, out); break
    case 'AssignmentPattern': patternNames(pattern.left, out); break
    default: break
  }
}

// File-wide declaration set, enough for module-scope audits; block scoping only ever hides a
// name that is declared somewhere and is therefore never reported.
export function undeclaredIdentifiers(source) {
  const ast = acorn.parse(source, { ecmaVersion: 'latest', sourceType: 'module', allowHashBang: true, locations: true })
  const declared = new Set()
  const referenced = new Map()
  walk(ast, (node, parent, key) => {
    switch (node.type) {
      case 'ImportSpecifier': case 'ImportDefaultSpecifier': case 'ImportNamespaceSpecifier':
        declared.add(node.local.name); return
      case 'VariableDeclarator': patternNames(node.id, declared); return
      case 'FunctionDeclaration': case 'FunctionExpression': case 'ArrowFunctionExpression':
        if (node.id) declared.add(node.id.name)
        for (const param of node.params) patternNames(param, declared)
        return
      case 'ClassDeclaration': case 'ClassExpression':
        if (node.id) declared.add(node.id.name)
        return
      case 'CatchClause': patternNames(node.param, declared); return
      case 'Identifier': break
      default: return
    }
    if (!parent) return
    if (parent.type === 'MemberExpression' && key === 'property' && !parent.computed) return
    if (parent.type === 'Property' && key === 'key' && !parent.computed && parent.value !== node) return
    if (parent.type === 'MethodDefinition' && key === 'key' && !parent.computed) return
    if (parent.type === 'PropertyDefinition' && key === 'key' && !parent.computed) return
    if (parent.type === 'ImportAttribute') return
    if (parent.type === 'LabeledStatement' || parent.type === 'BreakStatement' || parent.type === 'ContinueStatement') return
    if (parent.type === 'ImportSpecifier' || parent.type === 'ExportSpecifier') return
    if (parent.type === 'MetaProperty') return
    if (!referenced.has(node.name)) referenced.set(node.name, node.loc.start.line)
  })
  const free = []
  for (const [name, line] of referenced) {
    if (declared.has(name) || GLOBALS.has(name)) continue
    free.push({ name, line })
  }
  return free
}

test('the audit reports an identifier a module never declares or imports', () => {
  const free = undeclaredIdentifiers("export function run() { return missingHelper(1) }\n")
  assert.deepEqual(free, [{ name: 'missingHelper', line: 1 }])
})

test('the audit accepts imported, declared and global names', () => {
  const free = undeclaredIdentifiers([
    "import { readFileSync } from 'node:fs'",
    'export function run(value) {',
    '  const local = readFileSync(value)',
    '  const copy = { local, other: Math.max(1, JSON.parse("[]")) }',
    '  return copy.local && Math.random() && process.env && undefined',
    '}',
    ''
  ].join('\n'))
  assert.deepEqual(free, [])
})

test('every host-side plugin module declares or imports what it references', () => {
  const offenders = []
  for (const file of listModules(LIB)) {
    const free = undeclaredIdentifiers(fs.readFileSync(file, 'utf8'))
    if (!free.length) continue
    offenders.push(path.relative(ROOT, file) + ': ' + free.map(item => item.name + '@' + item.line).join(', '))
  }
  assert.deepEqual(offenders, [], 'undeclared identifiers:\n' + offenders.join('\n'))
})
