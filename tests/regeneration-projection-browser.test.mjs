test('连续三次重生成期间局部挂载，再发送新输入：不串轮、不需刷新恢复', async () => {
  const source = await readFile(new URL('../tavern-plugin/lib/client.js', import.meta.url), 'utf8')
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage()
    await page.setContent('<main></main>')
    const result = await page.evaluate(source => {
      window.__ModuleLoader__ = { load(d) { window.client = d.factory(() => ({})) } }
      window.eval(source)
      const root = document.querySelector('main')
      const projection = client.createTurnHistoryProjection({ root: () => root, storage: () => ({ getItem: () => '{}', removeItem() {} }) })
      function row(turn, kind, text) {
        const node = document.createElement('div')
        node.setAttribute('data-chat-flow-kind', kind)
        node.setAttribute('data-chat-turn', String(turn))
        node.textContent = text
        root.append(node)
        return node
      }
      const first = [row(2, 'user', '第一条输入'), row(2, 'assistant-step', '第一轮正文')]
      const input = row(3, 'user', '去花店看看')
      const old = row(3, 'assistant-step', '旧正文')
      const originalTail = row(3, 'turn-tail', '')
      const previousBodies = []
      const checks = []
      let latest
      // The server's plan while round 3 is regenerated by attempts 4, 5, 6: round 3 keeps
      // its input, earlier attempts draw nothing, the latest draws the round's reply.
      const planFor = turn => ({ turns: Object.fromEntries([[3, { input: 1, reply: 0 }],
        ...[4, 5, 6].filter(attempt => attempt < turn).map(attempt => [attempt, { input: 0, reply: 0 }]),
        [turn, { input: 0, reply: 1, story: 3 }]]), from: null })
      for (const turn of [4, 5, 6]) {
        // Native rows mount independently. Leave only the preceding body and
        // this replacement tail while its own input/context is not mounted.
        originalTail.remove(); input.remove(); old.remove()
        root.querySelectorAll('[data-chat-flow-kind="turn-tail"]').forEach(node => node.remove())
        const tail = row(turn, 'turn-tail', '')
        projection.apply('s', planFor(turn))
        checks.push(first.every(node => getComputedStyle(node).display !== 'none'))
        tail.remove()
        root.append(input, old, originalTail)
        row(turn, 'context', '内部重新生成指令')
        latest = row(turn, 'assistant-step', '新正文' + turn)
        root.append(tail)
        projection.apply('s', planFor(turn))
        checks.push(previousBodies.every(node => getComputedStyle(node).display === 'none'))
        previousBodies.push(latest)
        checks.push(getComputedStyle(input).display !== 'none' && getComputedStyle(old).display === 'none' && getComputedStyle(latest).display !== 'none')
      }
      const nextInput = row(7, 'user', '敲门问好')
      const nextBody = row(7, 'assistant-step', '有人开门')
      row(7, 'turn-tail', '')
      projection.apply('s', planFor(6))
      checks.push([nextInput, nextBody, latest, input, ...first].every(node => getComputedStyle(node).display !== 'none'))
      return checks
    }, source)
    assert.ok(result.every(Boolean), JSON.stringify(result))
  } finally { await browser.close() }
})

test('重生成期间只藏会被替代的正文：玩家的输入留在页面上', async () => {
  const source = await readFile(new URL('../tavern-plugin/lib/client.js', import.meta.url), 'utf8')
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage()
    await page.setContent('<main></main>')
    const result = await page.evaluate(source => {
      window.__ModuleLoader__ = { load(d) { window.client = d.factory(() => ({})) } }
      window.eval(source)
      const root = document.querySelector('main')
      const projection = client.createTurnHistoryProjection({ root: () => root, storage: () => ({ getItem: () => '{}', removeItem() {} }) })
      function row(turn, kind, text) {
        const node = document.createElement('div')
        node.setAttribute('data-chat-flow-kind', kind)
        node.setAttribute('data-chat-turn', String(turn))
        node.textContent = text
        root.append(node)
        return node
      }
      const input = row(1, 'user', '第一轮输入')
      const body = row(1, 'assistant-step', '第一轮正文')
      const tail = row(1, 'turn-tail', '')
      const hidden = node => getComputedStyle(node).display === 'none'
      // The server's plan while round 1's reply is being replaced.
      projection.apply('s', { turns: { 1: { input: 1, reply: 0 } }, from: null })
      const replacing = { input: hidden(input), body: hidden(body), tail: hidden(tail) }
      // 提交或中止后这一楼恢复正常：不能留下任何隐藏残留。
      projection.apply('s', { turns: {}, from: null })
      const restored = { input: hidden(input), body: hidden(body), tail: hidden(tail) }
      return { replacing, restored }
    }, source)
    assert.deepEqual(result.replacing, { input: false, body: true, tail: true }, '只藏正文和尾行，输入必须留着')
    assert.deepEqual(result.restored, { input: false, body: false, tail: false })
  } finally { await browser.close() }
})

test('已经显示出来的正文只被"搬走"，不会被重算的行计划抹掉', async () => {
  const source = await readFile(new URL('../tavern-plugin/lib/client.js', import.meta.url), 'utf8')
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage()
    await page.setContent('<main></main>')
    const result = await page.evaluate(source => {
      window.__ModuleLoader__ = { load(d) { window.client = d.factory(() => ({})) } }
      window.eval(source)
      const root = document.querySelector('main')
      const projection = client.createTurnHistoryProjection({ root: () => root, storage: () => ({ getItem: () => '{}', removeItem() {} }) })
      function row(turn, kind, text) {
        const node = document.createElement('div')
        node.setAttribute('data-chat-flow-kind', kind)
        if (turn !== null) node.setAttribute('data-chat-turn', String(turn))
        node.textContent = text
        root.append(node)
        return node
      }
      const hidden = node => getComputedStyle(node).display === 'none'
      const input = row(84, 'user', '玩家输入')
      const body = row(84, 'assistant-step', '已经输出的正文')
      const tail = row(84, 'turn-tail', '')
      // 正常状态：这一轮自己画输入与正文。
      projection.apply('s', { turns: {}, from: null })
      const drawn = hidden(body)
      // 重新生成刚开始：尝试轮 90 已经画这一轮的正文（计划会带上 story:84）——搬家，旧行照旧立刻收掉。
      projection.apply('s', { turns: { 84: { input: 1, reply: 0 }, 90: { input: 0, reply: 1, story: 84 } }, from: null }, undefined, { regenerating: true })
      const moved = hidden(body)
      // 尝试轮结束、投影还没落盘：计划一处都不画 story 84——这不是搬家，是抹掉，正文必须留着。
      projection.apply('s', { turns: { 84: { input: 1, reply: 0 }, 90: { input: 0, reply: 0 } }, from: null }, undefined, { regenerating: true })
      const gap = hidden(body)
      // 真的回退掉这一轮（连输入都不画了）：这才是删除，允许藏。
      projection.apply('s', { turns: { 84: { input: 0, reply: 0 } }, from: null })
      const removed = { body: hidden(body), input: hidden(input), tail: hidden(tail) }
      // 用户主动删掉这段正文（不是重新生成）：计划照删，不许留旧文。
      const kept = row(95, 'user', '另一轮输入')
      const deleted = row(95, 'assistant-step', '要删掉的正文')
      projection.apply('s', { turns: {}, from: null }, undefined, { regenerating: true })
      projection.apply('s', { turns: { 95: { input: 1, reply: 0 } }, from: null })
      return { drawn, moved, gap, removed, kept: hidden(kept), deleted: hidden(deleted) }
    }, source)
    assert.equal(result.drawn, false, '正常状态正文可见')
    assert.equal(result.moved, true, '正文搬到别的行时旧行可以藏')
    assert.equal(result.gap, false, '计划一处都不画时，已显示的正文不能被抹掉')
    assert.deepEqual(result.removed, { body: true, input: true, tail: true }, '回退掉的一轮照旧整轮藏起来')
    assert.deepEqual({ kept: result.kept, deleted: result.deleted }, { kept: false, deleted: true }, '用户主动删除正文时计划照删')
  } finally { await browser.close() }
})
