import { readFile, writeFile } from 'node:fs/promises'
import { stripTypeScriptTypes } from 'node:module'
const source = new URL('../tavern-plugin/lib/vendor/magvarupdate/upstream/src/function/schema.ts', import.meta.url)
const target = new URL('../tavern-plugin/lib/domain/mvu-schema.generated.js', import.meta.url)
const text = await readFile(source, 'utf8')
// Reuse the pinned MVU schema algorithm; only its pure JSON functions are included.
const generate = text.slice(text.indexOf('export function generateSchema('), text.indexOf('export function getSchemaForPath('))
const clean = text.slice(text.indexOf('function isMetaCarrier('))
const output = '// Generated by bin/build-mvu-schema.mjs from bundled MagVarUpdate (see vendor/magvarupdate/LICENSE).\n' +
  'const _ = {isObject: value => value !== null && typeof value === "object", isDate: value => value instanceof Date};\n' +
  'const isArraySchema = value => value?.type === "array", isObjectSchema = value => value?.type === "object";\n' +
  'const EXTENSIBLE_MARKER = "$__META_EXTENSIBLE__$";\n' + stripTypeScriptTypes(generate + '\n' + clean)
if (process.argv.includes('--check')) {
  if (await readFile(target,'utf8') !== output) throw Error('MVU schema artifact is stale')
} else await writeFile(target, output)
