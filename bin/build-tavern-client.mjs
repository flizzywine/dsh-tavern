import {prepareStageClientBuild} from '../tavern-plugin/packages/dsh-tavern-stage/build.mjs'
import {buildInterfaceSkinClient} from './build-interface-skin-client.mjs'
import { readFile, rename, unlink, writeFile } from 'node:fs/promises'
import path from 'node:path'
import vm from 'node:vm'
import { checkIncludedExports } from './lib/client-export-guard.mjs'
import { checkCssSyntax } from './lib/css-syntax-guard.mjs'
import { fileURLToPath } from 'node:url'
import forkSurfaces from '../tavern-plugin/src/client/surfaces.cjs'
// Public ./build entry of the independently owned shell client.

const root = fileURLToPath(new URL('..', import.meta.url))
const sourceRoot = path.join(root, 'tavern-plugin/src/client')
const modRoot = path.join(root, 'tavern-plugin/mods')
const templatePath = path.join(sourceRoot, 'main.js')
const outputPath = path.join(root, 'tavern-plugin/lib/client.js')
const banner = '// Generated by pnpm build:client; do not edit directly.\n'
const includePattern = /^([\t ]*)\/\/ @include(-domain|-protocol|-shared|-mod|-stage-source|-stage)? ([a-zA-Z0-9._/-]+)[\t ]*$/gm

function normalized(value) {
  return String(value).replace(/\r\n?/g, '\n').replace(/\s+$/, '') + '\n'
}

async function expand(source, seen) {
  // Widget definitions are CommonJS expression modules: one registry line works on both hosts.
  for (const match of [...source.matchAll(/require\('\.\/widgets\/([a-z][a-z0-9-]*)\.cjs'\)/g)].reverse()) {
    const relative = 'widgets/' + match[1] + '.cjs'
    const target = path.join(sourceRoot, relative)
    if (seen.has(target)) throw new Error('Duplicate widget definition: ' + relative)
    seen.add(target)
    const expression = normalized(await readFile(target, 'utf8')).trim()
    source = source.slice(0, match.index) + expression + source.slice(match.index + match[0].length)
  }
  const matches = [...source.matchAll(includePattern)]
  let output = source
  for (const match of matches.reverse()) {
    const relative = match[3]
    // Application-owned roots only: mod presenters are static source, never code from an imported pack.
    const includeRoot = match[2] === '-stage-source' ? path.join(root, 'tavern-plugin/packages/dsh-tavern-stage/src/client')
      : match[2] === '-stage' ? path.join(root, 'tavern-plugin/packages/dsh-tavern-stage/lib/client')
      : match[2] === '-mod' ? modRoot
      : match[2] === '-shared' ? path.join(root, 'tavern-plugin/shared')
      : match[2] === '-protocol' ? path.join(root, 'tavern-plugin/packages/dsh-presentation-protocol/src')
      : match[2] === '-domain' ? path.join(root, 'tavern-plugin/lib/domain') : sourceRoot
    const target = path.resolve(includeRoot, relative)
    if (path.relative(includeRoot, target).startsWith('..' + path.sep) || path.relative(includeRoot, target) === '..' || target === includeRoot) throw new Error(`客户端源码 include 越界: ${relative}`)
    if (seen.has(target)) throw new Error(`客户端源码重复 include: ${relative}`)
    seen.add(target)
    const imported = normalized(await readFile(target, 'utf8'))
    if (['-shared', '-domain', '-protocol', '-stage'].includes(match[2]) && target.endsWith('.cjs')) checkIncludedExports(imported, target)
    // Pure shared factories can export named symbols to Node; the classic browser
    // bundle embeds their declarations in its own scope.
    const fragment = await expand(match[2] === '-domain' ? imported.replace(/^export \{[^}]+\};?$/gm, '') : imported, seen)
    const indented = fragment.trimEnd().split('\n').map(line => line ? match[1] + line : '').join('\n')
    output = output.slice(0, match.index) + indented + output.slice(match.index + match[0].length)
  }
  return output
}

export async function assembleTavernClient() {
  forkSurfaces.validate(forkSurfaces.SURFACES)
  const template = normalized(await readFile(templatePath, 'utf8').then(value => value.replace(/\r\n?/g, '\n')))
  const readCss = async name => {
    const filename = path.join(root, 'tavern-plugin/lib/client-assets', name)
    const source = (await readFile(filename, 'utf8')).replace(/\r\n?/g, '\n')
    checkCssSyntax(source, filename)
    return source
  }
  // train always runs this builder with --check, even with an explicit test selection.
  const css = await readCss('tavern.css')
  const featureCss = await readCss('theme.css')
    + await readFile(path.join(root, 'tavern-plugin/lib/client-assets/layered-sprite.css'), 'utf8').then(value => value.replace(/\r\n?/g, '\n')).then(value => '\n' + value)
    + '\n' + await readFile(path.join(root, 'tavern-plugin/lib/client-assets/mod-config.css'), 'utf8').then(value => value.replace(/\r\n?/g, '\n'))
  // Keep the plugin theme at its original cascade position between shared rules.
  const featureParts = featureCss.split('/* @stage-theme-slot */')
  const keywordCatalogue = await readFile(path.join(root, 'tavern-plugin/shared/keyword-catalogue.cjs'), 'utf8').then(value => value.replace(/\r\n?/g, '\n'))
  const expanded = (await expand(template, new Set())).replace('__TAVERN_KEYWORD_CATALOGUE__', () => '(function () { const window = undefined, module = { exports: {} }; ' + keywordCatalogue + '; return module.exports; })()')
  const moods = expanded.includes('__TAVERN_BUBBLE_MOODS__')
    ? [] : null
  const brand = {}
  for (const name of ['logo', 'lockup', 'lockup-dark']) {
    const svg = await readFile(path.join(root, `tavern-plugin/lib/client-assets/${name}.svg`), 'utf8').then(value => value.replace(/\r\n?/g, '\n'))
    brand[name] = 'data:image/svg+xml,' + encodeURIComponent(svg.replace(/\s*\n\s*/g, ''))
  }
  return banner + normalized(expanded.replace('__TAVERN_BUNDLED_CSS__', () => JSON.stringify(css)).replace('__TAVERN_FEATURE_CSS__', () => JSON.stringify(featureParts)).replace('__TAVERN_BUBBLE_MOODS__', () => JSON.stringify(moods)).replace('__TAVERN_BRAND_URLS__', () => JSON.stringify(brand)))
}

export async function buildTavernClient({ check = false } = {}) {
  await buildInterfaceSkinClient({check})
  const stageBuild = await prepareStageClientBuild()
  const output = await assembleTavernClient()
  // Validate both sources before replacing either generated artifact.
  new vm.Script(output, { filename: outputPath })
  const current = await readFile(outputPath, 'utf8').then(value => value.replace(/\r\n?/g, '\n')).catch(() => '')
  if (check && stageBuild.changed) throw new Error('Stage client is stale; run build-tavern-client.mjs')
  if (check && current !== output) throw new Error('tavern-plugin/lib/client.js 已过期，请运行 pnpm build:client')
  await stageBuild.write()
  if (current === output) return Object.freeze({ changed: stageBuild.changed, path: outputPath })
  const temporary = outputPath + `.tmp-${process.pid}`
  try {
    await writeFile(temporary, output)
    await rename(temporary, outputPath)
  } finally {
    await unlink(temporary).catch(() => {})
  }
  return Object.freeze({ changed: true, path: outputPath })
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = await buildTavernClient({ check: process.argv.includes('--check') })
    console.log(result.changed ? '已生成 tavern-plugin/lib/client.js' : 'tavern-plugin/lib/client.js 已是最新')
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
