import {readFile, realpath, rename, unlink, writeFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
import vm from 'node:vm'

const output = new URL('./lib/client/skin-overlay.mjs', import.meta.url)
export async function prepareStageClientBuild() {
  const body = (await Promise.all(['motion','phase','timing','script','player'].map(name =>
    readFile(new URL((name === 'timing' ? './lib/client/skin-overlay-' : './src/client/skin-overlay-') + name + '.cjs', import.meta.url), 'utf8')
      .then(value => value.replace(/\r\n?/g, '\n'))))).join('\n')
  new vm.Script(body, {filename:fileURLToPath(output)})
  const next = '// Generated by dsh-tavern-stage/build; do not edit directly.\n' + body + '\nexport {createSkinOverlayPlayer,createDecorativeScript};\n'
  const css = (await Promise.all(['phone.css','textcard.css'].map(name =>
    readFile(new URL('./src/client/' + name, import.meta.url), 'utf8')))).join('\n')
  const theme = await readFile(new URL('./src/client/themes.css', import.meta.url), 'utf8')
  const navigation = await readFile(new URL('./src/client/navigation.cjs', import.meta.url), 'utf8')
  const views = await readFile(new URL('./src/client/views.cjs', import.meta.url), 'utf8')
  const text = await readFile(new URL('./src/client/text.cjs', import.meta.url), 'utf8')
  const labels = await readFile(new URL('./src/client/labels.cjs', import.meta.url), 'utf8')
  const loader = await readFile(new URL('./src/client/loader.cjs', import.meta.url), 'utf8')
  const admission = await readFile(new URL('./src/client/admission.cjs', import.meta.url), 'utf8')
  const progress = await readFile(new URL('./src/client/progress.cjs', import.meta.url), 'utf8')
  const template = await readFile(new URL('./src/client/entry.js', import.meta.url), 'utf8')
  const entry = '// Generated by dsh-tavern-stage/build; do not edit directly.\n' + template.replace('__STAGE_NAVIGATION__', () => navigation).replace('__STAGE_VIEWS__', () => views).replace('__STAGE_TEXT__', () => text).replace('__STAGE_LABELS__', () => labels).replace('__STAGE_LOADER__', () => loader).replace('__STAGE_ADMISSION__', () => admission).replace('__STAGE_PROGRESS__', () => progress).replace('__STAGE_PRESENTATION_CSS__', () => JSON.stringify(css)).replace('__STAGE_THEME_CSS__', () => JSON.stringify(theme))
  const entryOutput = new URL('./lib/client.js', import.meta.url)
  new vm.Script(entry, {filename:fileURLToPath(entryOutput)})
  const artifacts = await Promise.all([[output,next],[entryOutput,entry]].map(async ([file, content]) => {
    const current = await readFile(file, 'utf8').catch(error => {if (error.code === 'ENOENT') return ''; throw error})
    return {file, content, changed:current.replace(/\r\n?/g, '\n') !== content}
  }))
  return Object.freeze({
    changed:artifacts.some(item => item.changed),
    async write() {
      for (const {file,content,changed} of artifacts) {
        if (!changed) continue
        const temporary = new URL(file.href + '.tmp-' + process.pid)
        try {await writeFile(temporary, content); await rename(temporary, file)}
        finally {await unlink(temporary).catch(() => {})}
      }
    }
  })
}

export async function buildStageClient({check = false} = {}) {
  const build = await prepareStageClientBuild()
  if (check && build.changed) throw new Error('Stage client is stale; run dsh-tavern-stage/build')
  if (!check) await build.write()
  return {changed:build.changed}
}

if (process.argv[1] && await realpath(process.argv[1]).catch(() => '') === fileURLToPath(import.meta.url)) {
  await buildStageClient({check:process.argv.includes('--check')})
}
