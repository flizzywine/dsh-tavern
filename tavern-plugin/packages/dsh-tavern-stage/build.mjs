import {readFile, realpath, rename, unlink, writeFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
import vm from 'node:vm'

const output = new URL('./lib/client/skin-overlay.mjs', import.meta.url)
export async function prepareStageClientBuild() {
  const body = (await Promise.all(['motion','phase','timing','script','player'].map(name =>
    readFile(new URL((name === 'timing' ? './lib/client/skin-overlay-' : './src/client/skin-overlay-') + name + '.cjs', import.meta.url), 'utf8')
      .then(value => value.replace(/\r\n?/g, '\n'))))).join('\n')
  new vm.Script(body, {filename:fileURLToPath(output)})
  const next = '// Generated by dsh-tavern-stage/build; do not edit directly.\n' + body + '\nexport {createSkinOverlayPlayer,createDecorativeScript};\n'
  const current = await readFile(output, 'utf8').catch(error => {if (error.code === 'ENOENT') return ''; throw error})
  return Object.freeze({
    changed:current.replace(/\r\n?/g, '\n') !== next,
    async write() {
      if (current.replace(/\r\n?/g, '\n') === next) return
      const temporary = new URL(output.href + '.tmp-' + process.pid)
      try {await writeFile(temporary, next); await rename(temporary, output)}
      finally {await unlink(temporary).catch(() => {})}
    }
  })
}

export async function buildStageClient({check = false} = {}) {
  const build = await prepareStageClientBuild()
  if (check && build.changed) throw new Error('Stage client is stale; run dsh-tavern-stage/build')
  if (!check) await build.write()
  return {changed:build.changed}
}

if (process.argv[1] && await realpath(process.argv[1]).catch(() => '') === fileURLToPath(import.meta.url)) {
  await buildStageClient({check:process.argv.includes('--check')})
}
