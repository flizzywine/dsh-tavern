import { readFile, rename, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = new URL('./', import.meta.url)
const normalize = value => value.replace(/\r\n?/g, '\n')

export async function buildFateDiceClient({ check = false, packageRoot = root } = {}) {
  const src = normalize(await readFile(new URL('src/client/main.js', packageRoot), 'utf8'))
  const outputText = '// Generated by build.mjs; edit src/client/main.js.\n' + src.trimEnd() + '\n'
  new vm.Script(outputText, { filename: 'dsh-tavern-fate-dice/client.js' })
  const outUrl = new URL('client.js', packageRoot)
  const current = await readFile(outUrl, 'utf8').then(normalize).catch(err => {
    if (err.code === 'ENOENT') return ''
    throw err
  })
  if (current === outputText) return { changed: false }
  if (check) throw new Error('fate-dice client.js 已过期，请运行 node build.mjs')
  const tmp = fileURLToPath(outUrl) + '.tmp-' + process.pid
  try {
    await writeFile(tmp, outputText)
    await rename(tmp, outUrl)
  } finally {
    await rm(tmp, { force: true })
  }
  return { changed: true }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const res = await buildFateDiceClient({ check: process.argv.includes('--check') })
  console.log(res.changed ? 'built dsh-tavern-fate-dice/client.js' : 'up to date')
}
