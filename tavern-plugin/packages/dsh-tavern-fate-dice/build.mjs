import { readFile, rename, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = new URL('./', import.meta.url)
const normalize = value => value.replace(/\r\n?/g, '\n')

/* 固定拼接顺序：先常量/样式/桥接/基础组件，再挂件、工作台与两个标签页，最后注册与导出 */
export const CLIENT_SOURCE_FILES = [
  'presets.js',
  'styles.js',
  'bridge.js',
  'uikit.js',
  'dice-3d.js',
  'widgets.js',
  'pre-send-gate.js',
  'workbench.js',
  'tab-checks.js',
  'tab-settings.js',
  'main.js'
]

const HEADER = '// Generated by build.mjs; edit src/client/<module>.js and rebuild.\n'

function wrapSource(bodies) {
  const preamble = [
    'window.__ModuleLoader__.load({',
    "  id: 'dsh-tavern-fate-dice',",
    "  inject: ['tavernUi'],",
    '  factory: (require) => {',
    '    const module = { exports: {} }',
    '    const exports = module.exports',
    '    let React = null',
    '    try {',
    "      React = require('react')",
    '    } catch (error) {',
    "      try { console.warn('[dsh-tavern-fate-dice] React 不可用，浏览器界面已禁用:', error && error.message) } catch {}",
    '      exports.apply = () => {}',
    '      exports.inject = []',
    '      return module.exports',
    '    }',
    '    const h = React.createElement',
    '    const { Fragment, useEffect, useMemo, useRef, useState } = React',
    '    let ReactDOM = null',
    '    let ReactDOMClient = null',
    "    try { ReactDOM = require('react-dom') } catch {}",
    "    try { ReactDOMClient = require('react-dom/client') } catch {}",
    ''
  ].join('\n')

  const footer = ['', '    return module.exports', '  }', '})', ''].join('\n')
  return HEADER + preamble + bodies.join('\n\n') + footer
}

/* 契约自检：既防止工作台面板被误删，也防止发送栏按钮/手投弹窗回归 */
function assertClientContract(text) {
  if (!/\.registerPanel\s*\(/.test(text)) {
    throw new Error('client.js 契约失败：缺少 ui.registerPanel（右侧栏插件卡片区工作台）')
  }
  if (/registerComposerAction\s*\(/.test(text)) {
    throw new Error('client.js 契约失败：仍存在 registerComposerAction（发送栏骰盘按钮必须移除）')
  }
  if (/DicePadOverlay/.test(text)) {
    throw new Error('client.js 契约失败：仍存在 DicePadOverlay 手投弹窗')
  }
  const textareas = text.match(/<textarea/gi) || []
  if (textareas.length) {
    throw new Error('client.js 契约失败：出现裸 <textarea> 标签，请统一使用 FdArea 组件')
  }
}

export async function buildFateDiceClient({ check = false, packageRoot = root } = {}) {
  const bodies = []
  for (const file of CLIENT_SOURCE_FILES) {
    const source = normalize(await readFile(new URL(`src/client/${file}`, packageRoot), 'utf8')).trimEnd()
    bodies.push(`/* ===== src/client/${file} ===== */\n` + source)
  }
  const outputText = wrapSource(bodies)
  new vm.Script(outputText, { filename: 'dsh-tavern-fate-dice/client.js' })
  assertClientContract(outputText)

  const outUrl = new URL('client.js', packageRoot)
  const current = await readFile(outUrl, 'utf8').then(normalize).catch(err => {
    if (err.code === 'ENOENT') return ''
    throw err
  })
  if (current === outputText) return { changed: false }
  if (check) throw new Error('fate-dice client.js 已过期，请运行 node build.mjs')
  const tmp = fileURLToPath(outUrl) + '.tmp-' + process.pid
  try {
    await writeFile(tmp, outputText)
    await rename(tmp, outUrl)
  } finally {
    await rm(tmp, { force: true })
  }
  return { changed: true }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const res = await buildFateDiceClient({ check: process.argv.includes('--check') })
  console.log(res.changed ? 'built dsh-tavern-fate-dice/client.js' : 'up to date')
}
