import { readFile, rename, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = new URL('./', import.meta.url)
const normalize = value => value.replace(/\r\n?/g, '\n')

export const CLIENT_SOURCE_FILES = [
  'styles.js',
  'panel.js',
  'main.js'
]

const HEADER = '// Generated by build.mjs; edit src/client/<module>.js and rebuild.\n'

function wrapSource(bodies) {
  const preamble = [
    'window.__ModuleLoader__.load({',
    "  id: 'dsh-tavern-plot-compass',",
    "  inject: ['tavernUi'],",
    '  factory: (require) => {',
    '    const module = { exports: {} }',
    '    const exports = module.exports',
    '    let React = null',
    '    try {',
    "      React = require('react')",
    '    } catch (error) {',
    "      try { console.warn('[dsh-tavern-plot-compass] React 不可用，浏览器界面已禁用:', error && error.message) } catch {}",
    '      exports.apply = () => {}',
    '      exports.inject = []',
    '      return module.exports',
    '    }',
    '    const h = React.createElement',
    '    const { Fragment, useEffect, useState } = React',
    ''
  ].join('\n')

  const footer = ['', '    return module.exports', '  }', '})', ''].join('\n')
  return HEADER + preamble + bodies.join('\n\n') + footer
}

function assertClientContract(text) {
  if (!/\.registerPanel\s*\(/.test(text)) {
    throw new Error('client.js 契约失败：缺少 ui.registerPanel（剧情罗盘面板）')
  }
  if (!/plot-compass:state/.test(text)) {
    throw new Error('client.js 契约失败：缺少 plot-compass:state 宿主通信调用')
  }
}

export async function buildPlotCompassClient({ check = false, packageRoot = root } = {}) {
  const bodies = []
  for (const file of CLIENT_SOURCE_FILES) {
    const source = normalize(await readFile(new URL(`src/client/${file}`, packageRoot), 'utf8')).trimEnd()
    bodies.push(`/* ===== src/client/${file} ===== */\n` + source)
  }
  const outputText = wrapSource(bodies)
  new vm.Script(outputText, { filename: 'dsh-tavern-plot-compass/client.js' })
  assertClientContract(outputText)

  const outUrl = new URL('client.js', packageRoot)
  const current = await readFile(outUrl, 'utf8').then(normalize).catch(err => {
    if (err.code === 'ENOENT') return ''
    throw err
  })
  if (current === outputText) return { changed: false }
  if (check) throw new Error('dsh-tavern-plot-compass/client.js 已过期，请运行 node build.mjs')
  const tmp = fileURLToPath(outUrl) + '.tmp-' + process.pid
  try {
    await writeFile(tmp, outputText)
    await rename(tmp, outUrl)
  } finally {
    await rm(tmp, { force: true })
  }
  return { changed: true }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const res = await buildPlotCompassClient({ check: process.argv.includes('--check') })
  console.log(res.changed ? 'built dsh-tavern-plot-compass/client.js' : 'up to date')
}
