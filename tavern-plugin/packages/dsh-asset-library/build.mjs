// Remove generated files whose source was deleted; --check rejects stale surface too.
function prune(dir, relative = '') {
  for (const item of readdirSync(dir, {withFileTypes:true})) {
    // Aggregate host bundles are owned by bin/build-plugin-package.mjs, not this resource build.
    if (!relative && item.name === 'host' && item.isDirectory()) continue
    const name = join(relative, item.name), target = join(dir, item.name)
    if (item.isDirectory()) prune(target, name)
    else if (!sourceFiles.has(name)) {
      if (process.argv.includes('--check')) throw new Error('Obsolete build: ' + target)
      rmSync(target)
    }
  }
}
visit(join(root,'src'))
