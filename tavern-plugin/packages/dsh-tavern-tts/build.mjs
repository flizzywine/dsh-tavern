import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('.',import.meta.url))
const manifest = JSON.parse(readFileSync(join(root,'package.json'),'utf8'))
function emit(path, text) {
  if (process.argv.includes('--check')) { if (readFileSync(path,'utf8') !== text) throw new Error('Stale build: ' + path); return }
  mkdirSync(dirname(path),{recursive:true}); writeFileSync(path,text)
}
function visit(dir, relative = '') {
  for (const item of readdirSync(dir,{withFileTypes:true})) {
    const name = join(relative,item.name), path = join(dir,item.name)
    if (item.isDirectory()) visit(path,name)
    else if (name === 'client.css') continue
    else {
      let source = readFileSync(path,'utf8')
      // The panel stylesheet ships inside the client bundle (no Tavern dependency).
      if (name === 'client.js') source = source.replace("'/* client.css is inlined by build.mjs */'", () => JSON.stringify(readFileSync(join(root,'src/client.css'),'utf8')))
      emit(join(root,'lib',name), name === 'client.js' ? '// Generated by build.mjs; do not edit.\nwindow.__ModuleLoader__.load({id:' + JSON.stringify(manifest.name) + ',factory:(require)=>{const exports={};\n' + source + '\nreturn exports;}});\n' : source)
    }
  }
}
emit(join(root,'src/shared/voice-schema.js'), readFileSync(join(root,'../dsh-presentation-protocol/src/voice-schema.js'),'utf8'))
emit(join(root,'src/shared/voice-cues.cjs'), '// Generated from dsh-presentation-protocol by build.mjs; do not edit.\n' + readFileSync(join(root,'../dsh-presentation-protocol/src/voice-cues.cjs'),'utf8'))
emit(join(root,'src/shared/tts-messages.cjs'), '// Generated from dsh-presentation-protocol by build.mjs; do not edit.\n' + readFileSync(join(root,'../dsh-presentation-protocol/src/tts-messages.cjs'),'utf8'))
for (const name of ['native-settings.js', 'settings-migration.js']) {
  emit(join(root, 'src/shared', name), '// Generated from Tavern host settings by build.mjs; do not edit.\n' +
    readFileSync(join(root, '../../lib', name), 'utf8'))
}
emit(join(root, 'src/shared/request-origin.js'), '// Generated from Tavern host HTTP routes by build.mjs; do not edit.\n' +
  readFileSync(join(root, '../../lib/http/request-origin.js'), 'utf8'))
visit(join(root,'src'))
